-- INFORME 1: Asociaciones de futbol profesional
-- Asociaciones de tipo profesional (P) creadas despues del año 2000,
-- ordenadas en forma descendente por fecha de creacion.
SELECT 'ID:' || id_asociacion || ' * ' || nombre_asociacion AS "ASOCIACION",
       fecha_creacion                                       AS "CREADA",
       tipo_asociacion                                      AS "TIPO"
FROM asociacion
WHERE tipo_asociacion = 'P'
  AND fecha_creacion > DATE '2000-12-31'
ORDER BY fecha_creacion DESC;

-- INFORME 2: Patrimonio de clubes de futbol
-- Clubes con la letra a en su nombre, patrimonio superior a $200.000.000
-- y de tipo profesional. Conversion a dolares con un tipo de cambio de $955.
-- Ordenados en forma descendente por codigo del club.
SELECT id_club            AS "CLUB",
       nombre_club        AS "NOMBRE CLUB",
       patrimonio         AS "PATRIMONIO EN PESOS",
       patrimonio / 955   AS "PATRIMONIO EN DOLARES"
FROM club_futbol
WHERE nombre_club LIKE '%a%'
  AND patrimonio > 200000000
  AND tipo_club = 'Profesional'
ORDER BY id_club DESC;
